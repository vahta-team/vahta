//! Deterministic transcripts for the Kotlin/Dart side to verify against.
//!
//! The checked-in `tests/vectors.json` is regenerated with
//! `VAHTA_UPDATE_VECTORS=1 cargo test -p vahta-link --test vectors`; the test
//! otherwise fails if the code no longer produces the file byte for byte. The
//! keys are fixed test keys, never used anywhere else.

use serde_json::{Value, json};
use vahta_link::ble_frame::chunk_frame;
use vahta_link::channel::{Handshake, Keypair};
use vahta_link::messages::*;
use vahta_link::{Channel, Message, PairAccept, PairOffer, Partial};

const NOW: u64 = 1_000_000;

fn hx(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

fn fixed(n: u8) -> [u8; 32] {
    let mut k = [0u8; 32];
    for (i, b) in k.iter_mut().enumerate() {
        *b = n.wrapping_mul(17).wrapping_add(i as u8);
    }
    k
}

fn drive(i: &mut Handshake, r: &mut Handshake) -> Vec<Vec<u8>> {
    let mut frames = Vec::new();
    while !(i.is_finished() && r.is_finished()) {
        if i.is_my_turn() {
            let f = i.write().unwrap();
            r.read(&f).unwrap();
            frames.push(f);
        } else {
            let f = r.write().unwrap();
            i.read(&f).unwrap();
            frames.push(f);
        }
    }
    frames
}

fn one(c: &mut Channel, m: &Message) -> Vec<Vec<u8>> {
    c.seal_message(m).unwrap()
}

fn open(c: &mut Channel, frames: &[Vec<u8>]) -> Message {
    let mut p = Partial::default();
    let mut out = None;
    for f in frames {
        out = c.open_message(&mut p, f).unwrap();
    }
    out.unwrap()
}

fn build() -> Value {
    let desktop = Keypair::from_private(&fixed(1)).unwrap();
    let phone = Keypair::from_private(&fixed(2)).unwrap();
    let (de, pe) = (fixed(3), fixed(4));
    let vault = [0x42u8; 16];
    let mut offer = PairOffer::new(desktop.public, vault, "desk", NOW, 120).unwrap();
    offer.psk = fixed(5);

    // Pairing (XXpsk3).
    let mut i = Handshake::pairing_for_vectors(&desktop, &offer, NOW, true, &de).unwrap();
    let mut r = Handshake::pairing_for_vectors(&phone, &offer, NOW, false, &pe).unwrap();
    let hs = drive(&mut i, &mut r);
    let (mut dc, mut pc) = (i.finish().unwrap(), r.finish().unwrap());
    assert_eq!(dc.handshake_hash(), pc.handshake_hash());
    let pair_hash = hx(dc.handshake_hash());
    let accept = PairAccept {
        phone_name: "pixel".into(),
        phone_static_pub: phone.public,
        sign_pub: [&[4u8][..], &[0xA1; 64]].concat(),
        ecdh_pub: [&[4u8][..], &[0xB2; 64]].concat(),
    };
    let accept_msg = Message::PairAccept(accept);
    let accept_frames = one(&mut pc, &accept_msg);
    assert_eq!(open(&mut dc, &accept_frames), accept_msg);
    let ack_frames = one(&mut dc, &Message::PairAck);
    assert_eq!(open(&mut pc, &ack_frames), Message::PairAck);

    // Session (KK).
    let mut i = Handshake::session_for_vectors(&desktop, &phone.public, &vault, true, &de).unwrap();
    let mut r =
        Handshake::session_for_vectors(&phone, &desktop.public, &vault, false, &pe).unwrap();
    let shs = drive(&mut i, &mut r);
    let (mut dc, mut pc) = (i.finish().unwrap(), r.finish().unwrap());
    let session_hash = hx(dc.handshake_hash());
    let req = Message::ApproveRequest(ApproveRequest::new(
        b"vahta test request".to_vec(),
        [7; 16],
        NOW + 30,
    ));
    let req_frames = one(&mut dc, &req);
    assert_eq!(open(&mut pc, &req_frames), req);
    let Message::ApproveRequest(ar) = &req else {
        unreachable!()
    };
    let dec = Message::Decision(Decision {
        request_hash: ar.request_hash,
        choice: Choice::Approve,
        signature: vec![0xC3; 64],
    });
    let dec_frames = one(&mut pc, &dec);
    assert_eq!(open(&mut dc, &dec_frames), dec);

    let msgs: Vec<(&str, Message)> = vec![
        ("ping", Message::Ping(7)),
        ("pong", Message::Pong(7)),
        ("pair_ack", Message::PairAck),
        ("approve_request", req.clone()),
        ("decision", dec.clone()),
        (
            "unlock_request",
            Message::UnlockRequest(UnlockRequest {
                slot_id: vec![9; 16],
                eph_pub: [&[4u8][..], &[0xD4; 64]].concat(),
            }),
        ),
        (
            "unlock_response_secret",
            Message::UnlockResponse(UnlockResponse::SharedSecret(vec![0xE5; 32])),
        ),
        (
            "unlock_response_error",
            Message::UnlockResponse(UnlockResponse::Error("refused".into())),
        ),
    ];
    let frames_hex = |f: &[Vec<u8>]| f.iter().map(|x| hx(x)).collect::<Vec<_>>();
    let chunk_in: Vec<u8> = (0..50u8).collect();

    json!({
        "comment": "Test keys only. Generated by crates/link/tests/vectors.rs.",
        "protocol": { "pairing": vahta_link::channel::PAIRING_PATTERN, "session": vahta_link::channel::SESSION_PATTERN,
            "prologue": "ASCII 'vahta-link/1/pair|' or 'vahta-link/1/session|' followed by the 16 vault_id bytes",
            "message_envelope": "version byte (1) then postcard; fragment plaintext = flag (0 more, 1 last) then data" },
        "keys": {
            "desktop_static_private": hx(&desktop.private[..]), "desktop_static_public": hx(&desktop.public),
            "phone_static_private": hx(&phone.private[..]), "phone_static_public": hx(&phone.public),
            "desktop_ephemeral_private": hx(&de), "phone_ephemeral_private": hx(&pe),
            "psk": hx(&offer.psk), "vault_id": hx(&vault), "now": NOW,
        },
        "offer": { "qr_string": offer.to_qr_string(), "expires_at": offer.expires_at, "desktop_name": "desk" },
        "pairing": {
            "handshake_frames": frames_hex(&hs), "handshake_hash": pair_hash,
            "phone_to_desktop_pair_accept_frames": frames_hex(&accept_frames),
            "desktop_to_phone_pair_ack_frames": frames_hex(&ack_frames),
        },
        "session": {
            "handshake_frames": frames_hex(&shs), "handshake_hash": session_hash,
            "desktop_to_phone_approve_request_frames": frames_hex(&req_frames),
            "phone_to_desktop_decision_frames": frames_hex(&dec_frames),
        },
        "messages": msgs.iter().map(|(n, m)| json!({ "name": n, "encoded": hx(&m.encode()) })).collect::<Vec<_>>(),
        "ble_framing": { "frame": hx(&chunk_in), "chunk_len": 20,
            "chunks": chunk_frame(&chunk_in, 20).unwrap().iter().map(|c| hx(c)).collect::<Vec<_>>() },
        "base64url": { "input": "fbff", "output": b64_encode(&[0xfb, 0xff]) },
    })
}

/// Keys in sorted order whatever serde_json's map type is (another crate in the
/// workspace turns on `preserve_order`).
fn canon(v: Value) -> Value {
    match v {
        Value::Object(m) => {
            let mut e: Vec<_> = m.into_iter().collect();
            e.sort_by(|a, b| a.0.cmp(&b.0));
            Value::Object(e.into_iter().map(|(k, v)| (k, canon(v))).collect())
        }
        Value::Array(a) => Value::Array(a.into_iter().map(canon).collect()),
        v => v,
    }
}

#[test]
fn vectors_match_the_checked_in_file() {
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/tests/vectors.json");
    let got = serde_json::to_string_pretty(&canon(build())).unwrap() + "\n";
    if std::env::var_os("VAHTA_UPDATE_VECTORS").is_some() {
        std::fs::write(path, &got).unwrap();
        return;
    }
    let want = std::fs::read_to_string(path).expect("run with VAHTA_UPDATE_VECTORS=1 to create it");
    assert_eq!(
        got, want,
        "vectors changed; if intended, regenerate with VAHTA_UPDATE_VECTORS=1"
    );
}

#[test]
fn vectors_are_deterministic() {
    assert_eq!(build(), build());
}
